import { expect, test } from '@playwright/test'
import { load, open } from './helpers'

test('quiz start/loading/checked/results and replacement confirmation render in both themes', async ({ page }, info): Promise<void> => {
  await open(page, 1801)
  await load(page)
  await page.getByRole('button', { name: 'Quiz', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Generate quiz', exact: true })).toBeEnabled()
  await page.screenshot({ path: info.outputPath('quiz-start-dark.png') })
  await page.getByRole('button', { name: 'Generate quiz', exact: true }).click()
  await expect(page.getByRole('progressbar', { name: 'Generating quiz', exact: true })).toBeVisible()
  await page.screenshot({ path: info.outputPath('quiz-loading-dark.png') })
  await expect(page.getByRole('article', { name: 'Quiz question 1', exact: true })).toBeVisible()
  await page.screenshot({ path: info.outputPath('quiz-ready-dark.png') })
  await page.getByRole('radio', { name: 'Each always starts a separate network request.', exact: true }).check()
  await page.getByRole('button', { name: 'Check answer', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Not quite.', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Switch to light theme', exact: true }).click()
  await page.screenshot({ path: info.outputPath('quiz-checked-light.png') })
  await page.getByRole('button', { name: 'Question 5', exact: true }).click()
  await page.getByRole('button', { name: 'See results', exact: true }).click()
  await page.screenshot({ path: info.outputPath('quiz-results-light.png') })
  await page.getByRole('button', { name: 'Regenerate quiz', exact: true }).click()
  await page.screenshot({ path: info.outputPath('quiz-replacement-dialog.png') })
  await page.getByRole('dialog').getByRole('button', { name: 'Keep current result', exact: true }).click()
})

test('semantic start/loading and large complete remainder retain readable desktop geometry', async ({ page }, info): Promise<void> => {
  await open(page, 1802)
  await page.setExtraHTTPHeaders({ 'X-Sheldon-Scenario': 'large-source' })
  await load(page, 80)
  await page.getByRole('button', { name: 'Semantic review', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Generate semantic review', exact: true })).toBeEnabled()
  await page.screenshot({ path: info.outputPath('semantic-start-dark.png') })
  await page.getByRole('button', { name: 'Generate semantic review', exact: true }).click()
  await expect(page.getByRole('progressbar', { name: 'Generating semantic review', exact: true })).toBeVisible()
  await page.screenshot({ path: info.outputPath('semantic-loading-dark.png') })
  await expect(page.getByRole('heading', { name: 'One refresh, many callers', exact: true })).toBeVisible()
  await page.getByRole('navigation', { name: 'Semantic groups', exact: true }).getByRole('button', { name: /Ungrouped changes/ }).click()
  await expect(page.getByRole('article', { name: /^Remaining file / })).toHaveCount(80)
  await page.screenshot({ path: info.outputPath('semantic-large-remainder-dark.png') })
})
