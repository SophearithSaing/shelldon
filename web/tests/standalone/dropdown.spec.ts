import { expect, test } from '@playwright/test'
import { ask, completed, compose, load, open } from './helpers'

test('CSS-customized conversation picker preserves native selection, dismissal and keyboard behavior', async ({ page }, info): Promise<void> => {
  await open(page, 2101)
  await load(page)
  const title = 'Explain the cleanup boundary and the failure behavior for concurrent refresh requests without losing the original source context.'
  await completed(await ask(page, title))
  const initial = await compose(page, 18)
  await initial.getByRole('textbox').fill('Why share the refresh promise?')
  await initial.getByRole('button', { name: 'Send question', exact: true }).click()
  const inline = page.getByRole('region', { name: 'Inline conversation', exact: true }).last()
  await completed(inline)
  await inline.getByRole('button', { name: 'Open in panel', exact: true }).click()
  let admissions = 0
  page.on('request', (request): void => { if (request.method() === 'POST' && /\/(questions|answers)$/.test(request.url())) admissions++ })
  const selector = page.getByRole('combobox', { name: 'Choose conversation', exact: true })
  await expect(selector).toHaveCSS('appearance', 'base-select')
  const firstID = await selector.locator('option').first().getAttribute('value')
  const secondID = await selector.inputValue()
  if (!firstID) throw new Error('Expected original thread option.')
  await selector.click()
  await expect(page.locator('select:open')).toHaveCount(1)
  await expect(selector.locator('option').first()).toBeVisible()
  const picker = await selector.evaluate((element): { radius: string; background: string } => {
    const style = getComputedStyle(element, '::picker(select)')
    return { radius: style.borderRadius, background: style.backgroundColor }
  })
  expect(picker).toEqual({ radius: '8px', background: 'rgb(24, 25, 28)' })
  await page.screenshot({ path: info.outputPath('conversation-picker-dark.png') })
  await page.keyboard.press('Escape')
  await expect(selector.locator('option').first()).toBeHidden()
  await expect(selector).toBeFocused()
  await expect(selector).toHaveValue(secondID)
  await page.getByRole('button', { name: 'Switch to light theme', exact: true }).click()
  await selector.click()
  await expect(selector.locator('option').first()).toBeVisible()
  await page.screenshot({ path: info.outputPath('conversation-picker-light.png') })
  await selector.locator('option').first().click()
  await expect(selector).toHaveValue(firstID)
  await expect(selector.locator('option').first()).toBeHidden()
  await expect(page.getByRole('region', { name: 'Conversation', exact: true })).toContainText(title)
  await expect(selector).toHaveCSS('white-space', 'nowrap')
  await expect(selector.locator('selectedcontent')).toHaveCSS('text-overflow', 'ellipsis')
  const fieldBox = await selector.boundingBox()
  const valueBox = await selector.locator('selectedcontent').boundingBox()
  if (!fieldBox || !valueBox) throw new Error('Expected selected conversation label.')
  expect(valueBox.x + valueBox.width).toBeLessThanOrEqual(fieldBox.x + fieldBox.width - 40)
  await page.screenshot({ path: info.outputPath('conversation-picker-long-selection.png') })
  await selector.click()
  await page.keyboard.press('End')
  await page.keyboard.press('Enter')
  await expect(selector).toHaveValue(secondID)
  await expect(selector).toBeFocused()
  await page.setViewportSize({ width: 700, height: 900 })
  await selector.scrollIntoViewIfNeeded()
  await selector.click()
  await expect(selector.locator('option').first()).toBeVisible()
  const optionBox = await selector.locator('option').first().boundingBox()
  if (!optionBox) throw new Error('Expected visible option menu.')
  expect(optionBox.x).toBeGreaterThanOrEqual(0)
  expect(optionBox.x + optionBox.width).toBeLessThanOrEqual(700)
  await page.screenshot({ path: info.outputPath('conversation-picker-narrow.png') })
  await page.mouse.click(5, 5)
  await expect(selector.locator('option').first()).toBeHidden()
  expect(admissions).toBe(0)
})
